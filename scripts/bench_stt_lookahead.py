#!/usr/bin/env python3
"""Measure Nemotron streaming accuracy at several lookaheads.

The checkpoint's own attention context is ``[56, 13]``: 1.04 s of right
context and a 1.12 s native chunk. Halving the lookahead halves the chunk,
so partial text refreshes twice as often, at some cost in accuracy. This
script measures that cost on the same cached FLEURS clips the WER harness
uses, with the same text normalizers.

It drives the model directly and varies one session's
``att_context_size`` through ``scripts.stt_lookahead.apply_session_lookahead``
— the same function ``scripts/stt_server.py`` installs on the realtime
endpoint. The model's own default is never changed, so batch transcription
keeps the checkpoint default.

The published number is the **mean per-clip WER**, not corpus-level WER:
the paired bootstrap needs one observation per clip. The JSON keeps the
per-clip scores, so the interval can be recomputed without the model.

Usage:
    uv run python scripts/bench_stt_lookahead.py --clips 40 --lookaheads 13,6
    uv run python scripts/bench_stt_lookahead.py --clips 40 --lookaheads 13,6,3,0

The clips are generated by ``evals/wer_eval.py``; this script only reads
them and fails rather than silently measuring a smaller corpus.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import wave
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from evals.wer_eval import normalize_indic, normalize_standard  # noqa: E402
from scripts.stt_lookahead import (  # noqa: E402
    FRAME_MS,
    apply_session_lookahead,
    parse_lookahead,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
AUDIO_DIR = REPO_ROOT / "evals" / "fixtures" / "audio"
OUT_PATH = REPO_ROOT / "data" / "stt_lookahead_bench.json"
DEFAULT_MODEL = "mlx-community/nemotron-3.5-asr-streaming-0.6b"
LANGUAGES = {"en": ("en_us", "en-US"), "hi": ("hi_in", "hi-IN")}
DEFAULT_LOOKAHEADS = "13,6"
BOOTSTRAP_SEED = 20261027
BOOTSTRAP_SAMPLES = 20_000


@dataclass(frozen=True)
class Clip:
    language: str
    path: Path
    reference: str


def parse_lookaheads(raw: str) -> list[int]:
    """Turn ``"13,6"`` into ``[13, 6]``, rejecting gaps and duplicates."""
    frames: list[int] = []
    for piece in str(raw).split(","):
        text = piece.strip()
        if not text:
            continue
        value = parse_lookahead(text)
        if value is None:  # pragma: no cover - unreachable for a non-blank piece
            continue
        if value in frames:
            raise ValueError(f"duplicate lookahead {value}")
        frames.append(value)
    if not frames:
        raise ValueError("pass at least one lookahead, e.g. --lookaheads 13,6")
    return frames


def native_chunk_ms(frames: int) -> int:
    """One native encoder chunk: the right context plus the current frame."""
    return (frames + 1) * FRAME_MS


def score_text(reference: str, hypothesis: str, language: str) -> tuple[float, float]:
    """Per-clip WER and CER, with the repo's normalizer for the language."""
    import jiwer

    normalize = normalize_indic if language == "hi" else normalize_standard
    ref = normalize(reference)
    hyp = normalize(hypothesis)
    if not ref.strip() or not hyp.strip():
        return 1.0, 1.0
    return float(jiwer.wer(ref, hyp)), float(jiwer.cer(ref, hyp))


def summarize(
    language: str,
    lookahead: int,
    wers: list[float],
    cers: list[float],
    clips: list[str],
    seconds: float,
) -> dict:
    """Aggregate one arm's per-clip fractions into the reported row."""
    if not wers or not cers or not clips:
        raise ValueError(f"no clips to summarize for {language}@{lookahead}")
    if not len(wers) == len(cers) == len(clips):
        raise ValueError("wers, cers and clips must have the same length")
    return {
        "language": language,
        "lookahead": lookahead,
        "native_chunk_ms": native_chunk_ms(lookahead),
        "wer": round(float(np.mean(wers)) * 100, 2),
        "cer": round(float(np.mean(cers)) * 100, 2),
        "n": len(wers),
        "seconds": round(seconds, 1),
        "clips": list(clips),
        "wers": [round(value * 100, 4) for value in wers],
        "cers": [round(value * 100, 4) for value in cers],
    }


def paired_bootstrap(
    base: list[float],
    short: list[float],
    *,
    samples: int = BOOTSTRAP_SAMPLES,
    seed: int = BOOTSTRAP_SEED,
) -> dict:
    """95 % percentile CI for ``short - base``, resampling clips, not arms.

    Both arms saw the same clips in the same order, so the resampling unit
    is the clip index. A negative number means the shorter lookahead was
    better on this corpus; positive means it cost accuracy.
    """
    a = np.asarray(base, dtype=float)
    b = np.asarray(short, dtype=float)
    if a.shape != b.shape:
        raise ValueError("the two arms must have the same number of clips")
    if a.size == 0:
        raise ValueError("no clips to resample")
    diff = b - a
    rng = np.random.default_rng(seed)
    means = np.empty(samples)
    for index in range(samples):
        picks = rng.integers(0, diff.size, diff.size)
        means[index] = diff[picks].mean()
    lo, hi = np.percentile(means, [2.5, 97.5])
    return {
        "mean": round(float(diff.mean()), 4),
        "lo": round(float(lo), 4),
        "hi": round(float(hi), 4),
        "worse": int((diff > 0).sum()),
        "better": int((diff < 0).sum()),
        "tied": int((diff == 0).sum()),
        "n": int(diff.size),
        "samples": samples,
        "seed": seed,
    }


def load_cached_clips(languages: list[str], per_language: int) -> list[Clip]:
    """Read the cached FLEURS clips and refuse to measure a smaller corpus."""
    clips: list[Clip] = []
    for language in languages:
        if language not in LANGUAGES:
            raise ValueError(f"unknown language {language!r}; known: {sorted(LANGUAGES)}")
        config, _ = LANGUAGES[language]
        directory = AUDIO_DIR / config
        usable = [
            path
            for path in sorted(directory.glob("*.wav"))
            if (directory / f"{path.stem}.txt").exists()
        ]
        if len(usable) < per_language:
            raise SystemExit(
                f"bench_stt_lookahead: {config} has {len(usable)} usable clips, "
                f"need {per_language}; run "
                f"`uv run python evals/wer_eval.py --languages {language} "
                f"--per-language {per_language}` first"
            )
        for path in usable[:per_language]:
            clips.append(
                Clip(
                    language=language,
                    path=path,
                    reference=(directory / f"{path.stem}.txt").read_text(
                        encoding="utf-8"
                    ),
                )
            )
    return clips


def read_wav(path: Path) -> np.ndarray:
    import soxr

    with wave.open(str(path)) as handle:
        data = np.frombuffer(handle.readframes(handle.getnframes()), dtype="<i2")
        if handle.getnchannels() == 2:
            data = data.reshape(-1, 2).mean(axis=1).astype("<i2")
        rate = handle.getframerate()
    audio = data.astype(np.float32) / 32768.0
    return soxr.resample(audio, rate, 16000) if rate != 16000 else audio


def new_session(model, language: str, lookahead: int):
    session = model.create_streaming_session(language=language)
    return apply_session_lookahead(session, lookahead)


def drain(session, into: list[str]) -> None:
    """Run cooperative steps until the session has nothing ready.

    ``step`` only ingests queued audio when the encoder is empty, so a
    no-delta step with nothing encoded or queued means this batch is done.
    This mirrors the server's decoder loop; the private attributes are the
    only way the session exposes that state.
    """
    while True:
        deltas = session.step(max_decode_tokens=64)
        into.extend(deltas)
        if session.done:
            return
        if not deltas and not session._encoded and session._queued == 0:
            return


def transcribe(model, path: Path, language: str, lookahead: int) -> str:
    audio = read_wav(path)
    session = new_session(model, language, lookahead)
    parts: list[str] = []
    step = 5120  # 320 ms of 16 kHz audio per feed
    try:
        for offset in range(0, len(audio), step):
            session.feed(audio[offset : offset + step])
            drain(session, parts)
        session.close()
        while not session.done:
            drain(session, parts)
    finally:
        if not session.done:
            session.close()
    return "".join(parts).strip()


def run_arm(
    model, clips: list[Clip], language: str, lookahead: int
) -> dict:
    started = time.perf_counter()
    wers: list[float] = []
    cers: list[float] = []
    for clip in clips:
        hypothesis = transcribe(model, clip.path, LANGUAGES[language][1], lookahead)
        wer, cer = score_text(clip.reference, hypothesis, language)
        wers.append(wer)
        cers.append(cer)
        print(f"  {clip.path.stem}: {hypothesis[:64]!r}", flush=True)
    return summarize(
        language,
        lookahead,
        wers,
        cers,
        [clip.path.stem for clip in clips],
        time.perf_counter() - started,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--clips", type=int, default=40)
    parser.add_argument("--lookaheads", default=DEFAULT_LOOKAHEADS)
    parser.add_argument("--languages", nargs="+", default=["en", "hi"])
    parser.add_argument("--output", type=Path, default=OUT_PATH)
    args = parser.parse_args()

    try:
        lookaheads = parse_lookaheads(args.lookaheads)
        clips = load_cached_clips(args.languages, args.clips)
    except (ValueError, SystemExit) as exc:
        print(str(exc), file=sys.stderr)
        return 2

    print(f"model:     {args.model}")
    print(f"languages: {args.languages}")
    print(f"clips:     {args.clips} per language")
    print(f"lookahead: {lookaheads}\n")

    from mlx_audio.stt import load_model

    model = load_model(args.model)
    results: dict[str, dict] = {}
    for language in args.languages:
        subset = [clip for clip in clips if clip.language == language]
        print(f"=== {language} ===", flush=True)
        for lookahead in lookaheads:
            row = run_arm(model, subset, language, lookahead)
            results[f"{language}@{lookahead}"] = row
            print(
                f"{language} lookahead {lookahead:>2}: "
                f"chunk {row['native_chunk_ms']:>4} ms  "
                f"WER {row['wer']:>6.2f}%  CER {row['cer']:>6.2f}%  "
                f"({row['seconds']}s)",
                flush=True,
            )

    paired: dict[str, dict] = {}
    for language in args.languages:
        base = results.get(f"{language}@13")
        short = results.get(f"{language}@6")
        if base and short:
            paired[language] = paired_bootstrap(base["wers"], short["wers"])
            row = paired[language]
            print(
                f"{language}: mean 6-13 = {row['mean']:+.3f} points "
                f"(95% CI {row['lo']:+.3f} .. {row['hi']:+.3f}), "
                f"worse {row['worse']}, better {row['better']}, "
                f"tied {row['tied']} of {row['n']}",
                flush=True,
            )

    report = {
        "model": args.model,
        "measured_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "clips_per_language": args.clips,
        "lookaheads": lookaheads,
        "normalization": (
            "mean per-clip WER/CER after whisper-normalizer BasicTextNormalizer("
            "preserve_marks=True) for en, indicnlp normalize.indic_normalize for hi"
        ),
        "results": results,
        "paired_6_minus_13": paired,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"\nwrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
